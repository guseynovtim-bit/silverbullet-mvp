// Шаблон промпта для AI-резюме квартала. Общий для сервера (формирует запрос
// к Yandex GPT) и потенциально для тестов/сторибука — секретов не содержит,
// поэтому безопасен для импорта и в клиентский, и в серверный код.

export const SUMMARY_SYSTEM_MESSAGE =
  'Отвечай строго валидным JSON без markdown-разметки и без пояснений вне JSON-объекта.';

export function buildQuarterSummaryPrompt(jsonInput) {
  return `Рассуждай как опытный директор по продукту в крупной технологической компании. Твоя задача проанализировать итоги квартала на основе предоставленных данных и сформулировать краткое, но содержательное резюме для трёх разных аудиторий.

Входные данные (JSON): ${jsonInput}

Требования к ответу:

1. Общий итог квартала (1–2 предложения): коротко и ёмко что получилось, на что важно обратить внимание - используй в качестве контекста все данные.
2. Для топ‑менеджмента (1 абзац): фокус на деньгах и масштабе (MAU, ARPU, выручка‑эквивалент, риски по деньгам). Используй только данные из JSON. Не придумывай цифры.
3. Для проектного офиса (1 абзац): фокус на исполнении (задачи, релизы, загрузка и численность команды, отставания).
4. Для продуктовой команды (1 абзац): фокус на продукте (конверсия, отток, достижения, планы).

Формат вывода строго JSON: { "summary_overall": "...", "for_c_level": "...", "for_project_office": "...", "for_product_team": "..." }
Тон: деловой, но понятный нетехническим сотрудникам. Избегай жаргона. Статусы OK/Risk/Attention используй только если они явно следуют из данных.`;
}

export const SUMMARY_REQUIRED_KEYS = ['summary_overall', 'for_c_level', 'for_project_office', 'for_product_team'];
